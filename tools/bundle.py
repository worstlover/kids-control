#!/usr/bin/env python3
"""Inline supabase/functions/_shared/* into each function -> supabase/single-file/<name>.ts
(for pasting into the Supabase dashboard editor, which has no folders / relative imports)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'supabase'
fx = root / 'functions'
out = root / 'single-file'
out.mkdir(exist_ok=True)
SHARED = ['logic', 'common', 'ai']          # dependency order
NPM = "import { createClient } from 'npm:@supabase/supabase-js@2';"

def strip(src: str) -> str:
    src = re.sub(r"^import [^\n]*from '[^']*';\n", '', src, flags=re.M)      # all single-line imports
    src = re.sub(r"^export (async function|function|const|type|class|interface)", r"\1", src, flags=re.M)
    return src.strip() + '\n'

for d in sorted(p for p in fx.iterdir() if p.is_dir() and not p.name.startswith('_')):
    main = (d / 'index.ts').read_text()
    used = [m for m in SHARED if f"/_shared/{m}.ts" in main]
    # ai.ts needs logic, common is needed by anything calling admin()
    if 'ai' in used and 'logic' not in used: used.append('logic')
    used = [m for m in SHARED if m in used]
    parts = [f"// {d.name} — single-file build for the Supabase dashboard (generated by tools/bundle.py; edit supabase/functions/ instead)\n"]
    if 'common' in used: parts.append(NPM + '\n')
    for m in used:
        parts.append(f"// ---- shared/{m} ----\n" + strip((fx / '_shared' / f'{m}.ts').read_text()))
    parts.append("// ---- function ----\n" + strip(main))
    (out / f'{d.name}.ts').write_text('\n'.join(parts))
    print(d.name, len(used), 'shared modules,', (out / f'{d.name}.ts').stat().st_size, 'bytes')
